export const ALL_SLUG = 'all';

export const getAllImages = () =>
  galleryAlbums.flatMap((album) => album.images);

export const getAlbumBySlug = (slug) => {
  if (slug === ALL_SLUG) {
    return {
      category: 'All Events',
      slug: ALL_SLUG,
      coverImage: galleryAlbums[0]?.coverImage,
      images: getAllImages(),
    };
  }
  return galleryAlbums.find((album) => album.slug === slug) || null;
};
